function buildLexicalContent(sections: { heading: string; paragraphs: string[] }[]): Record<string, unknown> {
  const children: unknown[] = []

  for (const section of sections) {
    children.push({
      type: 'heading',
      tag: 'h2',
      format: 'right',
      indent: 0,
      version: 1,
      children: [{ text: section.heading, type: 'text', version: 1 }],
    })

    for (const para of section.paragraphs) {
      children.push({
        type: 'paragraph',
        format: 'right',
        indent: 0,
        version: 1,
        children: [{ text: para, type: 'text', version: 1 }],
      })
    }
  }

  return {
    root: {
      type: 'root',
      format: 'right',
      indent: 0,
      version: 1,
      direction: 'rtl',
      children,
    },
  }
}

